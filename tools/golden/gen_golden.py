"""Generate reference vectors for astro_core tests (development only).

Planets, sunrise/sunset, lunations, lunar eclipses: JPL DE440 via skyfield (MIT). Houses, nodes, sidereal time:
Swiss Ephemeris via pyswisseph (AGPL) — used only here to produce numbers,
never linked into the app. Output: packages/astro_core/test/golden/*.json
and packages/astro_core/lib/src/pluto_table.dart.

    .venv/bin/python gen_golden.py

DE440_BSP overrides the path of de440.bsp (default: data/ next to this script).
"""
import json
import math
import os
import pathlib

import swisseph as swe
from skyfield import almanac, eclipselib
from skyfield.api import load, wgs84
from skyfield.framelib import ecliptic_frame, ecliptic_J2000_frame

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "packages/astro_core/test/golden"
OUT.mkdir(parents=True, exist_ok=True)

ts = load.timescale()
eph = load(os.environ.get("DE440_BSP", str(pathlib.Path(__file__).parent / "data/de440.bsp")))
earth = eph["earth"]
BODIES = {
    "sun": "sun", "moon": "moon", "mercury": "mercury", "venus": "venus",
    "mars": "mars barycenter", "jupiter": "jupiter barycenter", "saturn": "saturn barycenter",
    "uranus": "uranus barycenter", "neptune": "neptune barycenter", "pluto": "pluto barycenter",
}

# TT Julian days: J2000 plus a spread 1600–2150 with odd fractions.
dates = [2451545.0]
jd = 2305447.5 + 0.137  # 1600-01-01
while jd < 2506331.5:   # 2150
    dates.append(round(jd, 5))
    jd += 4999.731
planets = []
for d in dates:
    t = ts.tt_jd(d)
    row = {"jde": d, "deltaT": float(t.delta_t), "bodies": {}}
    for name, key in BODIES.items():
        lat, lon, dist = earth.at(t).observe(eph[key]).apparent().frame_latlon(ecliptic_frame)
        row["bodies"][name] = {"lon": lon.degrees, "lat": lat.degrees}
    jd_ut = d - float(t.delta_t) / 86400
    mean = swe.calc(d, swe.MEAN_NODE)[0][0]
    true = swe.calc(d, swe.TRUE_NODE)[0][0]
    row["meanNode"] = mean
    row["trueNode"] = true
    row["jdUt"] = jd_ut
    row["siderealDeg"] = swe.sidtime(jd_ut) * 15
    row["obliquity"] = swe.calc(d, swe.ECL_NUT)[0][0]
    planets.append(row)
(OUT / "planets.json").write_text(json.dumps(planets, indent=1))

# Houses from identical inputs (RAMC, latitude, obliquity).
SYSTEMS = {"placidus": b"P", "koch": b"K", "regiomontanus": b"R", "campanus": b"C",
           "porphyry": b"O", "equal": b"E", "wholeSign": b"W", "meridian": b"X", "morinus": b"M"}
houses = []
eps = 23.4392911
for lat in [0.0, 14.6, 50.0833, 60.0, 65.9, -33.92, -45.0, 70.0]:
    for ramc in [0.0, 37.5, 93.1, 151.2, 200.0, 271.7, 333.3]:
        row = {"lat": lat, "ramc": ramc, "eps": eps, "systems": {}}
        for name, code in SYSTEMS.items():
            if abs(lat) > 66 and name in ("placidus", "koch"):
                continue
            cusps, ascmc = swe.houses_armc(ramc, lat, eps, code)
            row["systems"][name] = list(cusps[:12])
            row["asc"], row["mc"] = ascmc[0], ascmc[1]
        houses.append(row)
(OUT / "houses.json").write_text(json.dumps(houses, indent=1))

# Pluto heliocentric J2000 ecliptic, every 30 days, 1550–2200 (DE440 range).
start = 2287184.5 + 30   # just after DE440 start (1549-12-31)
end = 2524593.5          # 2200
pluto, sun = eph["pluto barycenter"], eph["sun"]
xyz = []
n = 0
jd = start
while jd <= end:
    t = ts.tdb_jd(jd)
    x, y, z = (pluto.at(t) - sun.at(t)).frame_xyz(ecliptic_J2000_frame).au
    xyz += [x, y, z]
    n += 1
    jd += 30
lines = []
for i in range(0, len(xyz), 6):
    lines.append("  " + ", ".join(f"{v:.8f}" for v in xyz[i:i + 6]) + ",")
dart = f"""// GENERATED by tools/golden/gen_golden.py from JPL DE440 — do not edit.
// Heliocentric J2000 ecliptic rectangular coordinates of Pluto (AU),
// every 30 days (TT ≈ TDB), JD {start} … {start + (n - 1) * 30}.
const double _start = {start};
const double _step = 30;

bool covers(double jde) => jde >= _start + _step && jde < _start + (_xyz.length ~/ 3 - 2) * _step;

/// Cubic (4-point Lagrange) interpolation of the table.
({{double x, double y, double z}})? heliocentric(double jde) {{
  if (!covers(jde)) return null;
  final f = (jde - _start) / _step;
  final i = f.floor();
  final u = f - i;
  final w0 = -u * (u - 1) * (u - 2) / 6;
  final w1 = (u + 1) * (u - 1) * (u - 2) / 2;
  final w2 = -(u + 1) * u * (u - 2) / 2;
  final w3 = (u + 1) * u * (u - 1) / 6;
  double c(int k) =>
      w0 * _xyz[(i - 1) * 3 + k] + w1 * _xyz[i * 3 + k] + w2 * _xyz[(i + 1) * 3 + k] + w3 * _xyz[(i + 2) * 3 + k];
  return (x: c(0), y: c(1), z: c(2));
}}

const List<double> _xyz = [
{chr(10).join(lines)}
];
"""
(ROOT / "packages/astro_core/lib/src/pluto_table.dart").write_text(dart)

# R2: sunrise/sunset per local mean solar day (Sun's upper limb, -50').
PLACES = {
    "prague": (50.0833, 14.4167), "quito": (-0.22, -78.51), "sydney": (-33.87, 151.21),
    "tokyo": (35.68, 139.69), "los_angeles": (34.05, -118.24), "reykjavik": (64.15, -21.94),
    "tromso": (69.65, 18.96), "ushuaia": (-54.8, -68.3),
}
sun_rows = []
d0 = 2458850.5  # 2020-01-01
for name, (plat, plon) in PLACES.items():
    obs = earth + wgs84.latlon(plat, plon)
    for k in range(40):
        jd0 = d0 + k * 91.37  # spread over ten years and all seasons
        jd0 = math.floor(jd0 - 0.5) + 0.5
        t0 = jd0 - plon / 360
        ta, tb = ts.ut1_jd(t0), ts.ut1_jd(t0 + 1)
        rise, ry = almanac.find_risings(obs, eph["sun"], ta, tb, horizon_degrees=-50 / 60)
        sets, sy = almanac.find_settings(obs, eph["sun"], ta, tb, horizon_degrees=-50 / 60)
        r = [t.ut1 for t, ok in zip(rise, ry) if ok]
        s_ = [t.ut1 for t, ok in zip(sets, sy) if ok]
        y, m, d = ts.ut1_jd(jd0 + 0.5).ut1_calendar()[:3]
        sun_rows.append({"place": name, "lat": plat, "lon": plon, "date": [int(y), int(m), int(d)],
                         "rise": r[0] if r else None, "set": s_[0] if s_ else None})
(OUT / "sun.json").write_text(json.dumps(sun_rows, indent=1))

# R2: exact lunations (apparent ecliptic longitude of date, Moon - Sun = k * 90).
lun_rows = []
spans = [(2024, 2027)] + [(y, y + 1) for y in range(1700, 2151, 25)]
for y0, y1 in spans:
    t, ph = almanac.find_discrete(ts.utc(y0, 1, 1), ts.utc(y1, 1, 1), almanac.moon_phases(eph))
    for ti, pi in zip(t, ph):
        lun_rows.append({"jdUt": ti.ut1, "kind": int(pi)})
(OUT / "lunations.json").write_text(json.dumps(lun_rows, indent=1))

# R2: lunar eclipses (0 penumbral, 1 partial, 2 total), 2000-2030.
t, y, details = eclipselib.lunar_eclipses(ts.utc(2000, 1, 1), ts.utc(2031, 1, 1), eph)
ecl = [{"jdUt": ti.ut1, "type": int(yi)} for ti, yi in zip(t, y)]
(OUT / "lunar_eclipses.json").write_text(json.dumps(ecl, indent=1))

print(f"sun {len(sun_rows)}, lunations {len(lun_rows)}, lunar eclipses {len(ecl)}")
print(f"planets {len(planets)}, houses {len(houses)}, pluto rows {n}")
