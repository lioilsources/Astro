"""Fixed-star catalog and reference vectors for astro_core (development only).

Source: Hipparcos Main Catalogue (ESA 1997, CDS I/239), fetched from VizieR.
Praesepe is a cluster, not a single star: its centre and mean proper motion come
from Cantat-Gaudin et al. 2018 (A&A 618, A93, CDS J/A+A/618/A93, NGC 2632).
Both are distributed by CDS/VizieR with attribution (see docs/ephemeris.md).

Output:
  packages/astro_core/lib/src/star_catalog.dart  (J2000 RA/Dec + proper motion)
  packages/astro_core/test/golden/stars.json     (skyfield + DE440 apparent longitudes)

    .venv/bin/python gen_stars.py
"""
import json
import math
import os
import pathlib
import urllib.request

from skyfield.api import Star, load
from skyfield.framelib import ecliptic_frame

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
# GOLDEN_DATA overrides the data folder (e.g. a shared copy of de440.bsp).
DATA = pathlib.Path(os.environ.get("GOLDEN_DATA", HERE / "data"))
VIZIER = "https://vizier.cfa.harvard.edu/viz-bin/asu-tsv"

# Content id -> Hipparcos number. Order = order in the plan (10.6).
STARS = [
    ("algol", 14576), ("alcyone", 17702), ("aldebaran", 21421), ("rigel", 24436),
    ("bellatrix", 25336), ("capella", 24608), ("betelgeuse", 27989), ("sirius", 32349),
    ("castor", 36850), ("pollux", 37826), ("procyon", 37279), ("praesepe", None),
    ("alphard", 46390), ("regulus", 49669), ("denebola", 57632), ("vindemiatrix", 63608),
    ("algorab", 60965), ("spica", 65474), ("arcturus", 69673), ("zubenelgenubi", 72622),
    ("zubeneschamali", 74785), ("unukalhai", 77070), ("acrab", 78820), ("antares", 80763),
    ("rasalhague", 86032), ("vega", 91262), ("altair", 97649), ("deneb_algedi", 107556),
    ("fomalhaut", 113368), ("achernar", 7588), ("markab", 113963), ("scheat", 113881),
]


def fetch(name, query):
    path = DATA / name
    if not path.exists():
        DATA.mkdir(exist_ok=True)
        with urllib.request.urlopen(f"{VIZIER}?{query}", timeout=60) as r:
            path.write_bytes(r.read())
    rows = []
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        rows.append([c.strip() for c in line.split("\t")])
    header = rows[0]
    return [dict(zip(header, r)) for r in rows[2:]]  # skip the units row


hips = ",".join(str(h) for _, h in STARS if h)
hip_rows = fetch("hip_stars.tsv", f"-source=I/239/hip_main&-out=HIP,RAICRS,DEICRS,pmRA,pmDE,Plx,Vmag&-out.max=100&HIP={hips}")
hip = {int(r["HIP"]): r for r in hip_rows}
cl = fetch("praesepe.tsv", "-source=J/A%2BA/618/A93/table1&Cluster=NGC_2632&-out=Cluster,RAJ2000,DEJ2000,pmRA,pmDE,plx")[0]

MAS = 1 / 3_600_000
catalog = []  # id, hip, ra2000, dec2000, pmra*, pmdec, vmag, (epoch, ra, dec, plx) for skyfield
for sid, h in STARS:
    if h is None:
        ra, dec = float(cl["RAJ2000"]), float(cl["DEJ2000"])
        pmra, pmdec, plx, vmag, epoch = float(cl["pmRA"]), float(cl["pmDE"]), float(cl["plx"]), 3.7, 2015.5
    else:
        r = hip[h]
        ra, dec = float(r["RAICRS"]), float(r["DEICRS"])
        pmra, pmdec, plx, vmag, epoch = float(r["pmRA"]), float(r["pmDE"]), float(r["Plx"]), float(r["Vmag"]), 1991.25
    # Linear propagation to J2000.0 (the Dart side uses the same linear model).
    dt = 2000.0 - epoch
    ra2000 = ra + pmra * MAS * dt / math.cos(math.radians(dec))
    dec2000 = dec + pmdec * MAS * dt
    catalog.append(dict(id=sid, hip=h, ra=ra2000, dec=dec2000, pmra=pmra, pmdec=pmdec, vmag=vmag,
                        epoch=epoch, ra0=ra, dec0=dec, plx=plx))

rows = []
for s in catalog:
    hip_s = "null" if s["hip"] is None else str(s["hip"])
    rows.append(f"  ('{s['id']}', {hip_s}, {s['ra']:.8f}, {s['dec']:.8f}, {s['pmra']:.2f}, {s['pmdec']:.2f}, {s['vmag']:.2f}),")
dart = f"""// GENERATED by tools/golden/gen_stars.py — do not edit.
// Hipparcos Main Catalogue (ESA 1997, CDS I/239); Praesepe: Cantat-Gaudin et al. 2018
// (CDS J/A+A/618/A93, NGC 2632). Positions propagated linearly to J2000.0 (ICRS).
// Columns: content id, HIP number, RA (deg), Dec (deg), pm RA·cos(Dec) (mas/yr),
// pm Dec (mas/yr), V magnitude.
const List<(String, int?, double, double, double, double, double)> starRows = [
{chr(10).join(rows)}
];
"""
(ROOT / "packages/astro_core/lib/src/star_catalog.dart").write_text(dart)

# Golden: apparent geocentric ecliptic longitude of date, skyfield from the raw catalogue epoch.
ts = load.timescale()
eph = load(str(DATA / "de440.bsp"))
earth = eph["earth"]
years = [1800, 1900, 2000, 2050]
golden = []
for y in years:
    jde = 2451545.0 + (y - 2000) * 365.25
    t = ts.tt_jd(jde)
    row = {"year": y, "jde": jde, "stars": {}}
    for s in catalog:
        star = Star(ra_hours=s["ra0"] / 15, dec_degrees=s["dec0"], ra_mas_per_year=s["pmra"],
                    dec_mas_per_year=s["pmdec"], parallax_mas=s["plx"], epoch=ts.J(s["epoch"]))
        lat, lon, _ = earth.at(t).observe(star).apparent().frame_latlon(ecliptic_frame)
        row["stars"][s["id"]] = {"lon": lon.degrees, "lat": lat.degrees}
    golden.append(row)
(ROOT / "packages/astro_core/test/golden/stars.json").write_text(json.dumps(golden, indent=1))
for s in catalog:
    print(f"{s['id']:15s} V {s['vmag']:5.2f}  lon2000 {golden[2]['stars'][s['id']]['lon']:8.3f}")
